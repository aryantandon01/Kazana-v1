#!/usr/bin/env node
/**
 * Generate SQL to seed job_sources for ATS boards.
 *
 * Usage:
 *   node scripts/ingestion/generate-ats-sources-sql.js
 *   node scripts/ingestion/generate-ats-sources-sql.js --expansion-only
 */
import { readFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { greenhouseBoards, leverBoards } from './data/ats-boards.js';
import { ashbyBoards } from './data/ashby-boards.js';
import { workdayBoards } from './data/workday-boards.js';
import { eightfoldBoards } from './data/eightfold-boards.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '../..');
const CRON_MINUTES = 180;

const LICENSES = {
  greenhouse: 'Greenhouse Job Board API — https://boards-api.greenhouse.io',
  lever: 'Lever Postings API — https://api.lever.co',
  ashby: 'Ashby Job Postings API — https://api.ashbyhq.com/posting-api',
  workday: 'Workday CXS API — public career site JSON endpoints',
  eightfold: 'Eightfold PCSX API — public career site JSON endpoints',
};

function slugFor(provider, board) {
  switch (provider) {
    case 'greenhouse':
      return `gh-${board.boardToken}`.toLowerCase();
    case 'lever':
      return `lever-${board.boardToken}`.toLowerCase();
    case 'ashby':
      return `ashby-${board.boardToken}`.toLowerCase();
    case 'workday':
      return `wd-${board.tenant}`.toLowerCase();
    case 'eightfold':
      return `ef-${board.host}`.toLowerCase();
    default:
      throw new Error(`Unknown provider: ${provider}`);
  }
}

function configFor(provider, board) {
  const base = {
    provider,
    company_name: board.companyName,
  };

  if (provider === 'workday') {
    return {
      ...base,
      board_token: board.tenant,
      tenant: board.tenant,
      wd_server: board.wdServer,
      site: board.site,
    };
  }

  if (provider === 'eightfold') {
    return {
      ...base,
      board_token: board.host,
      host: board.host,
      domain: board.domain,
    };
  }

  return {
    ...base,
    board_token: board.boardToken,
  };
}

function loadExistingSlugs() {
  const slugs = new Set(['remotive', 'weworkremotely-programming']);
  const migrationsDir = join(ROOT, 'db/migrations');

  for (const file of readdirSync(migrationsDir)) {
    if (!file.endsWith('.sql')) continue;
    const sql = readFileSync(join(migrationsDir, file), 'utf8');
    for (const match of sql.matchAll(/'((?:gh|lever|ashby|wd|ef)-[^']+)'/g)) {
      slugs.add(match[1]);
    }
  }

  return slugs;
}

function providerLabel(provider) {
  return provider.charAt(0).toUpperCase() + provider.slice(1);
}

function buildRow(provider, board) {
  const slug = slugFor(provider, board);
  const config = JSON.stringify(configFor(provider, board));

  return `  (
    '${slug}',
    '${board.companyName.replace(/'/g, "''")} (${providerLabel(provider)})',
    'api',
    '${LICENSES[provider]}',
    '${config}'::jsonb,
    true,
    ${CRON_MINUTES}
  )`;
}

const expansionOnly = process.argv.includes('--expansion-only');
const existingSlugs = expansionOnly ? loadExistingSlugs() : new Set();

const allBoards = [
  ...greenhouseBoards.map((board) => ({ provider: 'greenhouse', board })),
  ...leverBoards.map((board) => ({ provider: 'lever', board })),
  ...ashbyBoards.map((board) => ({ provider: 'ashby', board })),
  ...workdayBoards.map((board) => ({ provider: 'workday', board })),
  ...eightfoldBoards.map((board) => ({ provider: 'eightfold', board })),
];

const boards = expansionOnly
  ? allBoards.filter(({ provider, board }) => !existingSlugs.has(slugFor(provider, board)))
  : allBoards;

const rows = boards.map(({ provider, board }) => buildRow(provider, board));

const header = expansionOnly
  ? `-- New ATS job sources only (${rows.length} boards)
-- Skips slugs already present in prior migrations.
-- Generated by: node scripts/ingestion/generate-ats-sources-sql.js --expansion-only`
  : `-- ATS job sources (${rows.length} boards)
-- Generated by: node scripts/ingestion/generate-ats-sources-sql.js`;

if (rows.length === 0) {
  console.log(`${header}\n\n-- No new job sources to insert.\n`);
  process.exit(0);
}

console.log(`${header}

INSERT INTO job_sources (slug, name, source_type, license, config, is_active, cron_interval_minutes)
VALUES
${rows.join(',\n')}
ON CONFLICT (slug) DO NOTHING;
`);
